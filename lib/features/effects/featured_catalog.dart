/// The 18 bands of the graphic equalizer, as `superequalizer` names them.
final List<String> kSuperequalizerBands = [
  for (var i = 1; i <= 18; i++) '${i}b',
];

DoubleParam _band(String key) => DoubleParam(
  key,
  min: 0,
  max: 20,
  def: 1,
  get: (e) => (e as SuperequalizerEffect).params[key] ?? 1,
  set: (e, v) {
    final eq = e as SuperequalizerEffect;
    final params = Map<String, double>.from(eq.params);
    if (v == 1) {
      params.remove(key);
    } else {
      params[key] = v;
    }
    return eq.copyWith(params: params);
  },
);

List<({String label, Object value})> _options<E extends Enum>(
  List<E> values,
  String Function(E) wire,
) => [for (final o in values) (label: wire(o), value: o as Object)];

