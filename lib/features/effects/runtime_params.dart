/// Whether turning [from] into [to] moves only options the running graph
/// takes live, so a slider drag can be heard as it moves. A change that
/// would rebuild the filter is better sent once, when the drag ends.
bool changesLive(AudioEffect from, AudioEffect to) {
  if (from.runtimeType != to.runtimeType || from.enabled != to.enabled) {
    return false;
  }
  final d = descriptorOf(to.filter);
  if (d == null) return from == to;
  final live = kRuntimeParams[d.name] ?? const <String>{};
  for (final ParamSpec p in d.params) {
    if (_value(p, from) != _value(p, to) && !live.contains(p.name)) {
      return false;
    }
  }
  return true;
}

Object? _value(ParamSpec p, AudioEffect e) => switch (p) {
  DoubleParam d => d.get(e),
  IntParam i => i.get(e),
  BoolParam b => b.get(e),
  EnumParam en => en.get(e),
  StringParam s => s.get(e),
};
